import * as fs from 'fs';
import * as path from 'path';
import { ApplicationKbData } from './schema';
import { estimateTokenCount } from './tokens';

export interface SuiteIndexSummary {
  appsCount: number;
  totalTokens: number;
  apps: Array<{
    id: string;
    name: string;
    type: string;
    languages: string[];
    frameworks: string[];
    tldr: string;
    tokens: number;
    kbPath: string;
  }>;
  relationships: Array<{
    from: string;
    to: string;
    reason: string;
  }>;
}

export function generateKbIndex(
  kbList: ApplicationKbData[],
  outputFolder: string
): { indexMarkdown: string; suiteJson: string } {
  let totalTokens = 0;
  const appSummaries = kbList.map((app) => {
    totalTokens += app.frontMatter.tokens;
    return {
      id: app.frontMatter.id,
      name: app.frontMatter.name,
      type: app.frontMatter.type,
      languages: app.frontMatter.languages,
      frameworks: app.frontMatter.frameworks,
      tldr: app.tldr,
      tokens: app.frontMatter.tokens,
      kbPath: `./${app.frontMatter.id}.md`
    };
  });

  const relationships: Array<{ from: string; to: string; reason: string }> = [];
  for (const app of kbList) {
    for (const link of app.relatedApps) {
      relationships.push({
        from: app.frontMatter.id,
        to: link.targetAppId,
        reason: link.reason
      });
    }
  }

  const suiteData: SuiteIndexSummary = {
    appsCount: kbList.length,
    totalTokens,
    apps: appSummaries,
    relationships
  };

  const appRows = appSummaries
    .map(
      (a) =>
        `| [\`${a.id}\`](${a.kbPath}) | ${a.type} | ${a.languages.join(', ')} | ${a.tldr} | ~${a.tokens} |`
    )
    .join('\n');

  const relRows =
    relationships.length > 0
      ? relationships.map((r) => `| \`${r.from}\` | → | \`${r.to}\` | ${r.reason} |`).join('\n')
      : '| None detected | - | - | - |';

  const indexMarkdown = `# BuildContext Knowledge Base Index

> **Total Suite Tokens:** ~${totalTokens} tokens across ${kbList.length} applications.

## How AI Agents Should Use This Knowledge Base
1. Read this \`KB_INDEX.md\` first to get a complete overview of the workspace architecture.
2. Select **only the specific application KB file(s)** relevant to your current task.
3. Follow the **Conventions** and **Architecture** sections inside the chosen \`<app-id>.md\` file.

## Applications Directory
| Application KB | Type | Languages | Purpose / Summary | Approx Tokens |
|---|---|---|---|---|
${appRows}

## Suite Relationship Graph
| Source App | Direction | Target App | Relationship / Mechanism |
|---|---|---|---|
${relRows}

---
*Generated by BuildContext. Re-run \`BuildContext: Workspace\` to refresh context files.*
`;

  const suiteJson = JSON.stringify(suiteData, null, 2);

  return { indexMarkdown, suiteJson };
}
